public class PseudotoJava {
    public static void main(String[] args) {
        // Convert the given pseudocode into Java code
        int JHPD = 2;
        int AHPD = 1;
        int NOD = 5;
        
        int WJH = JHPD * NOD;
        int WAH = AHPD * NOD;
        int TPH = WJH + WAH;
        
        System.out.println("Java: " + WJH);
        System.out.println("Aptitude: " + WAH);
        System.out.println("Total: " + TPH);
    }
}

    
